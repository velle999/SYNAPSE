/*
 * edid_hdr_test.c — does the display panel know an HDR monitor when it sees one?
 *
 * The bug this pins: "is this an HDR display?" used to be answered by asking
 * the backend for a 10-bit framebuffer. Every 10-bit-capable GPU plane says
 * yes, so an HDR10 monitor and the SDR panel next to it produced identical
 * answers and the panel could not tell them apart.
 *
 * The fixtures are the two real DisplayPort monitors on the development desk,
 * captured from their sysfs connector EDIDs with the serial numbers zeroed and
 * the block checksums recomputed:
 *
 *   lg_hdr10_edid   — LG UltraGear, CTA HDR static metadata with SMPTE ST2084
 *                     (PQ) and a BT2020RGB/BT2020YCC colorimetry block
 *   pixio_sdr_edid  — Pixio PX248P, a CTA extension with neither block; it is
 *                     10-bit and SDR, which is exactly the case the old test
 *                     could not distinguish from the LG
 *
 * SynapseOS Project
 * SPDX-License-Identifier: GPL-2.0-or-later
 * https://github.com/velle999/SYNAPSE
 */

