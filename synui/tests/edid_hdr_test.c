int main(void)
{
    syn_edid_hdr_t h;

    /* The HDR10 monitor. PQ is what makes it HDR10; BT.2020 and the peak
     * luminance are what the detail line in the panel prints. */
    CHECK(edid_hdr_parse(lg_hdr10_edid, sizeof(lg_hdr10_edid), &h) == 1,
          "LG EDID failed to parse");
    CHECK(h.pq == 1, "LG: expected PQ (HDR10), got %d", h.pq);
    CHECK(h.hlg == 0, "LG: expected no HLG, got %d", h.hlg);
    CHECK(h.bt2020 == 1, "LG: expected BT.2020 colorimetry, got %d", h.bt2020);
    CHECK(h.max_nits > 351.0f && h.max_nits < 352.0f,
          "LG: expected ~351 cd/m2 peak, got %.2f", (double)h.max_nits);

    /* The SDR monitor, same desk, same 10-bit link. This is the assertion the
     * old framebuffer-format probe could not have made. */
    CHECK(edid_hdr_parse(pixio_sdr_edid, sizeof(pixio_sdr_edid), &h) == 1,
          "Pixio EDID failed to parse");
    CHECK(h.pq == 0 && h.hlg == 0,
          "Pixio: SDR panel reported HDR (pq=%d hlg=%d)", h.pq, h.hlg);
    CHECK(h.bt2020 == 0, "Pixio: expected no BT.2020, got %d", h.bt2020);
    CHECK(h.max_nits == 0.0f,
          "Pixio: expected no luminance, got %.2f", (double)h.max_nits);

    /* Garbage and short reads must zero the struct, not leave it stale — the
     * panel renders these fields unconditionally. A disconnected DP port's
     * sysfs edid attribute is genuinely zero-length. */
    h.pq = h.hlg = h.bt2020 = 1;
    h.max_nits = 1000.0f;
    CHECK(edid_hdr_parse(NULL, 0, &h) == 0, "NULL blob accepted");
    CHECK(h.pq == 0 && h.hlg == 0 && h.bt2020 == 0 && h.max_nits == 0.0f,
          "NULL blob left stale HDR fields");

    static const uint8_t junk[256] = { 0xde, 0xad, 0xbe, 0xef };
    h.pq = 1;
    CHECK(edid_hdr_parse(junk, sizeof(junk), &h) == 0 || h.pq == 0,
          "junk blob reported HDR");

    /* Truncated: a valid header but half a block. */
    CHECK(edid_hdr_parse(lg_hdr10_edid, 64, &h) == 0,
          "64-byte blob accepted as an EDID");

    /* Connector probe. There is no monitor on a build machine or in the ISO
     * build chroot, so this cannot assert a result — only that naming a
     * connector that does not exist is answered with 0 and a zeroed struct
     * rather than a crash or stale data. */
    h.pq = 1;
    CHECK(edid_hdr_probe_connector("NO-SUCH-CONNECTOR-42", &h) == 0,
          "missing connector reported an EDID");
    CHECK(h.pq == 0, "missing connector left stale HDR fields");
    CHECK(edid_hdr_probe_connector(NULL, &h) == 0, "NULL connector accepted");

    /* Informational: on the development desk this prints the real monitors,
     * which is how the panel's output was checked against edid-decode. */
    DIR *dir = opendir("/sys/class/drm");
    if (dir) {
        struct dirent *de;
        while ((de = readdir(dir))) {
            const char *dash = strncmp(de->d_name, "card", 4) == 0
                             ? strchr(de->d_name + 4, '-') : NULL;
            if (!dash || !edid_hdr_probe_connector(dash + 1, &h)) continue;
            printf("  %-12s pq=%d hlg=%d bt2020=%d peak=%.0f cd/m2\n",
                   dash + 1, h.pq, h.hlg, h.bt2020, (double)h.max_nits);
        }
        closedir(dir);
    }

    if (failures) {
        fprintf(stderr, "%d check(s) failed\n", failures);
        return 1;
    }
    printf("edid_hdr: all checks passed\n");
    return 0;
}
